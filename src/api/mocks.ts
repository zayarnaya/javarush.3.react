export interface StationInfo {
  station: string;
  code: string;
  time: string;
  date: string;
}

export type AvailabilityStatus = { type: 'available'; count: number } | { type: 'waitlist'; position: number };

export type FareType = 'General' | 'Tatkal';

export type ClassCode = '3A' | '2A' | '1A';

export interface TrainClass {
  classCode: ClassCode;
  className: string;
  availability: AvailabilityStatus;
  fareType: FareType;
  price: number;
}

export interface Train {
  id: number;
  trainNumber: string;
  trainName: string;
  from: StationInfo;
  to: StationInfo;
  duration: string;
  classes: TrainClass[];
}

